"""Build the lightweight Cinema Profile artwork index, keeping masters intact."""
from pathlib import Path
import hashlib, json, subprocess
from PIL import Image

repo = Path(__file__).resolve().parents[1]
site = repo / '1-Site'
script = '''const fs=require('fs'),path=require('path'),vm=require('vm');const root=process.argv[1];
const ctx=vm.createContext({});for(const name of ['cinema-profile-data.js','cinema-profile-visual.js','cinema-profile-scene-bank.js','cinema-profile-adaptive.js','cinema-profile-core.js','cinema-profile-counterframe.js'])vm.runInContext(fs.readFileSync(path.join(root,name),'utf8'),ctx);
const D=ctx.CinemaProfileData,CF=ctx.CinemaCounterframe;
const names=[...D.artworkNames,...D.films.flatMap(f=>[f.poster,f.still]),...[...D.questions,...D.adaptive.questions,...D.adaptive.refinement,...CF.questions].flatMap(q=>[q,...(q.forms||[])].flatMap(form=>form.filmId?[form.still]:form.options.map(o=>o.still)))].filter(Boolean).map(p=>p.startsWith('assets/')?p:'assets/films/'+p);
console.log(JSON.stringify([...new Set(names)]));'''
paths = json.loads(subprocess.check_output(['node','-e',script,str(site)],text=True,encoding='utf-8'))
sizes, variants = {}, {}
for filename in ['2010-2019','2020-2026','artwork-variants']:
    d=json.loads((site/'content'/f'{filename}.json').read_text(encoding='utf-8'))
    d=d.get('media',d)
    sizes.update(d.get('sizes',{})); variants.update(d.get('variants',{}))

def actual(path):
    candidate=site/path
    return candidate if candidate.exists() else repo/'2-Artwork/films'/Path(path).name

out={'sizes':{},'variants':{}}
created=0
for path in sorted(paths):
    src=actual(path)
    assert src.is_file(),path
    with Image.open(src) as image:
        w,h=image.size
        out['sizes'][path]=[w,h]
        records=[dict(v) for v in variants.get(path,[]) if actual(v['src']).is_file()]
        if not any(v['width']==w for v in records): records.append({'src':path,'width':w})
        # Reuse all existing variants. Add only materially smaller screen sizes
        # for originals which would otherwise be expensive on cards or choices.
        if src.stat().st_size>100*1024:
            widths=[176,320,480,640,960] if w/h<.9 else [320,640,960,1280]
            for desired in widths:
                if desired*1.2>=w or any(desired<=v['width']<=desired*1.35 for v in records): continue
                token=hashlib.sha1(path.encode()).hexdigest()[:10]
                dest=f'assets/films/responsive/profile-{token}-{desired}w.webp'
                dest_file=site/dest
                if not dest_file.exists():
                    scaled=image.convert('RGB').resize((desired,round(h*desired/w)),Image.Resampling.LANCZOS)
                    extra={'icc_profile':image.info['icc_profile']} if image.info.get('icc_profile') else {}
                    scaled.save(dest_file,quality=86,method=3,**extra)
                    created+=1
                records.append({'src':dest,'width':desired})
        out['variants'][path]=sorted({v['width']:v for v in records}.values(),key=lambda v:v['width'])

target=site/'cinema-profile-media.js'
target.write_text('/* Generated by tools/build-profile-media.py — original artwork is unchanged. */\n'+
                  'globalThis.ArchiveProfileMedia='+json.dumps(out,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8',newline='\n')
print(f'{len(paths)} profile artworks indexed; {created} new responsive variants; {target.stat().st_size} bytes.')
